// compatibilityChanges lists arguments that used to be forwarded or dropped
// silently and whose handling changes with this matrix. The doc generator and
// the tests both read it.
type compatibilityChange struct {
	Flag       string
	Subcommand string
	Before     string
	After      string
	Impact     string
}

func compatibilityChanges() []compatibilityChange {
	return []compatibilityChange{
		{
			Flag:       "--kernel-memory",
			Subcommand: "run, create",
			Before:     "forwarded unchanged; the runtime logs that the flag is a no-op",
			After:      "accepted, dropped with a warning that names the flag",
			Impact:     "scripts keep running; the warning now makes the lost limit visible",
		},
		{
			Flag:       "consistency= inside --mount",
			Subcommand: "run",
			Before:     "deleted silently and the remaining keys reordered by a map round-trip",
			After:      "deleted with a warning that names --mount and the dropped key; the remaining keys keep their order",
			Impact:     "scripts keep running; the command line becomes stable and the loss is visible",
		},
		{
			Flag:       "--expose, --publish-all, --link, --network-alias, --net-alias, --storage-opt, --volume-driver",
			Subcommand: "run, create",
			Before:     "forwarded and rejected later by the runtime with \"unknown flag\"",
			After:      "rejected by finch before the runtime runs, all at once, with a doc link",
			Impact:     "the command already failed; only the message and the timing change",
		},
		{
			Flag:       "everything else classified unsupported",
			Subcommand: "all",
			Before:     "forwarded and rejected later by the runtime one flag at a time",
			After:      "rejected by finch with every unsupported flag in one error",
			Impact:     "the command already failed; the fix is now a single round-trip",
		},
	}
}

// runtimeDefaults lists arguments where the docker default and the runtime
// default disagree, so an argument that is merely forwarded cannot reproduce
// docker behaviour.
type runtimeDefault struct {
	Flag        string
	Subcommands string
	Docker      string
	Runtime     string
	Mitigation  string
	Existing    string
}

func runtimeDefaults() []runtimeDefault {
	return []runtimeDefault{
		{
			Flag:        "--platform",
			Subcommands: "run, create, build",
			Docker:      "defaults to the DOCKER_DEFAULT_PLATFORM environment variable",
			Runtime:     "has no environment-based default",
			Mitigation:  "finch injects --platform=$DOCKER_DEFAULT_PLATFORM when the variable is set and the flag is absent",
			Existing:    "users who set the variable only get the docker behaviour now; users who do not set it see no change",
		},
		{
			Flag:        "--cpu-quota",
			Subcommands: "run, create",
			Docker:      "0 means unset",
			Runtime:     "-1 means unset and 0 means a zero quota",
			Mitigation:  "an explicit --cpu-quota 0 is rewritten to --cpu-quota -1",
			Existing:    "only users who passed 0 explicitly are affected, and they get the docker meaning back",
		},
	}
}

// RenderMarkdown renders the matrix, the compatibility list, the defaults
// section, and the path boundary into the documentation page.
func RenderMarkdown() string {
	var b strings.Builder

	b.WriteString("# Docker-style argument mapping\n\n")
	b.WriteString("Finch translates docker-style arguments into the arguments of the container\n")
	b.WriteString("runtime it drives. When `dockercompat: true` is set in `finch.yaml`, the\n")
	b.WriteString("translation applies to `run`, `create`, `exec`, and `build`.\n\n")
	b.WriteString("<!-- This file is generated by pkg/argtranslate/gen. Do not edit it by hand. -->\n\n")

	b.WriteString("## Categories\n\n")
	b.WriteString("Every argument falls into exactly one category.\n\n")
	b.WriteString("| Category | Meaning |\n")
	b.WriteString("| --- | --- |\n")
	b.WriteString("| `pass` | Forwarded unchanged, with the same name and value. |\n")
	b.WriteString("| `rewrite` | Renamed or given a fixed replacement value, then forwarded. |\n")
	// The row must stay on one physical markdown line, so it is split across Go
	// literals for readability and joined without a newline.
	b.WriteString("| `special` | The value needs sub-command aware surgery (path mapping, " +
		"`consistency=` removal, `host-gateway` resolution, `--cpu-quota 0`) " +
		"before forwarding. |\n")
	b.WriteString("| `ignored` | Accepted but not forwarded; a warning names the flag. " +
		"The rationale column states why dropping it is harmless. |\n")
	b.WriteString("| `unsupported` | Rejected before the runtime runs. Every unsupported flag is reported in one error. |\n\n")

	for _, m := range Matrices() {
		writeMatrix(&b, m)
	}

	b.WriteString("## Arguments that change behaviour\n\n")
	b.WriteString("These arguments used to be forwarded or dropped silently. They are listed here\n")
	b.WriteString("because the change is visible to existing scripts.\n\n")
	b.WriteString("| Argument | Sub-command | Before | After | Impact |\n")
	b.WriteString("| --- | --- | --- | --- | --- |\n")
	for _, c := range compatibilityChanges() {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", c.Flag, c.Subcommand, c.Before, c.After, c.Impact)
	}
	b.WriteString("\n")

	b.WriteString("### Lenient mode\n\n")
	b.WriteString("Setting `dockercompat_lenient: true` in `finch.yaml` turns an unsupported\n")
	b.WriteString("argument into a warning and drops it, so a script that relied on a flag being\n")
	b.WriteString("ignored keeps running. It is off by default.\n\n")
	b.WriteString("* Strict (default): one error lists every unsupported flag with the\n")
	b.WriteString("  sub-command and a link to this page. Old scripts break, but the failure is\n")
	b.WriteString("  complete and actionable.\n")
	b.WriteString("* Lenient: old scripts keep running, but a dropped argument can look applied\n")
	b.WriteString("  when it is not. Every drop is warned about by name.\n\n")

	b.WriteString("## Runtime defaults differ\n\n")
	b.WriteString("For these arguments, forwarding only what the user wrote cannot reproduce\n")
	b.WriteString("docker's behaviour, so the translator supplies a default.\n\n")
	b.WriteString("| Argument | Sub-commands | Docker default | Runtime default | What finch does | Effect on existing users |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- |\n")
	for _, d := range runtimeDefaults() {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s |\n",
			d.Flag, d.Subcommands, d.Docker, d.Runtime, d.Mitigation, d.Existing)
	}
	b.WriteString("\n")

	b.WriteString("## Where path conversion happens\n\n")
	b.WriteString("The translator decides *which* values are host paths and *what* to strip. It\n")
	b.WriteString("never knows how to convert them: the mapping is injected through\n")
	b.WriteString("`PathMapper.MapHostPath` and `HostGatewayResolver.ResolveHostGateway`. On\n")
	b.WriteString("macOS the mapper is the identity, because the host home directory is mounted\n")
	b.WriteString("into the VM at the same path. On Windows it maps a drive letter to\n")
	b.WriteString("`/mnt/<drive>`. Because the legacy per-argument handlers are bypassed once\n")
	b.WriteString("translation is active, a path is converted exactly once.\n\n")
	b.WriteString("Values mapped as host paths: the `-v`/`--volume` source, a `type=bind`\n")
	b.WriteString("`--mount` source, `--label-file`, `--cidfile`, `--cosign-key`, and the build\n")
	b.WriteString("`-f`/`--file`, `--iidfile`, `--output dest=`, `--secret src=`,\n")
	b.WriteString("`--cache-from`, `--cache-to`, `--build-context`, and the build context.\n\n")

	b.WriteString("### Environment files\n\n")
	b.WriteString("`--env-file` is forwarded with its path mapped, and the runtime reads the file\n")
	b.WriteString("inside the VM. The translator never opens the file. One consequence: a line\n")
	b.WriteString("that names a variable without a value is resolved against the environment\n")
	b.WriteString("inside the VM, whereas docker resolves it on the host. Use an explicit\n")
	b.WriteString("`-e NAME` if the host value is the one you want; that case is resolved on the\n")
	b.WriteString("host and forwarded as `NAME=value`.\n\n")

	b.WriteString("## Not covered\n\n")
	b.WriteString("`compose`, `inspect`, `cp`, and `save`/`load` keep their existing handlers and\n")
	b.WriteString("are not part of this matrix.\n")
	return b.String()
}

func writeMatrix(b *strings.Builder, m Matrix) {
	fmt.Fprintf(b, "## finch %s\n\n", m.Subcommand)
	b.WriteString("| Flag | Kind | Category | Forwarded as | Notes |\n")
	b.WriteString("| --- | --- | --- | --- | --- |\n")
	for _, e := range m.Entries {
		fmt.Fprintf(b, "| `%s` | %s | `%s` | %s | %s |\n",
			flagCell(e), e.Kind, e.Category, forwardedAs(e), noteCell(e))
	}
	b.WriteString("\n")
}

func flagCell(e Entry) string {
	if e.Short != "" {
		return "--" + e.Name + ", -" + e.Short
	}
	return "--" + e.Name
}

func forwardedAs(e Entry) string {
	switch e.Category {
	case CatPass:
		return "same flag"
	case CatRewrite:
		if e.RuntimeName != "" && e.RuntimeValue != "" {
			return fmt.Sprintf("`--%s=%s`", e.RuntimeName, e.RuntimeValue)
		}
		if e.RuntimeName != "" {
			return "`--" + e.RuntimeName + "`"
		}
		return "same flag"
	case CatSpecial:
		switch e.Special {
		case SpecialCPUQuota:
			return "same flag, `0` becomes `-1`"
		case SpecialEnv:
			return "same flag, a bare `NAME` is resolved from the host environment"
		case SpecialMount:
			return "same flag, bind sources mapped, `consistency` dropped"
		default:
			return "same flag, value rewritten as `" + e.Syntax + "`"
		}
	case CatIgnored:
		return "not forwarded"
	case CatUnsupported:
		return "rejected"
	}
	return ""
}

func noteCell(e Entry) string {
	switch e.Category {
	case CatIgnored:
		return e.Rationale
	case CatUnsupported:
		if e.Note == "" {
			return "not supported by the runtime"
		}
		return e.Note
	case CatSpecial:
		if e.Syntax != "" {
			return "expects `" + e.Syntax + "`"
		}
	}
	if e.Note == "" {
		return "-"
	}
	return e.Note
}
